package com.go.craft.gojar;

import java.io.IOException;
import java.lang.classfile.ClassFile;
import java.lang.classfile.ClassModel;
import java.lang.classfile.FieldModel;
import java.lang.classfile.MethodModel;
import java.lang.constant.ClassDesc;
import java.lang.constant.MethodTypeDesc;
import java.lang.reflect.AccessFlag;
import java.nio.charset.StandardCharsets;
import java.nio.file.FileSystem;
import java.nio.file.FileSystems;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

/**
 * Generates typed Go wrappers from the game's own class files. Only classes listed under [bindings]
 * are generated: Java packages import each other in cycles that Go forbids, so everything lands in
 * one Go package, and a full dump would make every mod pay to compile thousands of unused types.
 * Types outside the list appear as jvm.Object.
 */
final class Bindings {
	static final int VERSION = 1;
	private static final Set<String> KEYWORDS = Set.of("break", "default", "func", "interface", "select", "case", "defer", "go", "map", "struct",
			"chan", "else", "goto", "package", "switch", "const", "fallthrough", "if", "range", "type", "continue", "for", "import", "return", "var", "string", "error", "len", "new", "nil");
	/** Promoted from jvm.Object, so a generated method of this name would change its meaning. */
	private static final Set<String> RESERVED_METHODS = Set.of("JavaObject", "IsNull", "IsInstance", "ClassOf", "String");

	private final Project project;

	Bindings(Project project) {
		this.project = project;
	}

	void generate(Path outRoot) throws IOException, InterruptedException {
		Path jar = new Runs(project, Map.of()).clientJar();
		List<String> include = project.list("bindings", "include");
		String packageName = project.string("bindings", "package", "mcgen");
		Map<String, ClassModel> models = new TreeMap<>();

		try (FileSystem fs = FileSystems.newFileSystem(jar)) {
			Path root = fs.getPath("/");
			try (var stream = Files.walk(root)) {
				for (Path file : stream.filter(p -> p.toString().endsWith(".class")).toList()) {
					String internal = root.relativize(file).toString().replace(".class", "");
					if (matches(internal.replace('/', '.'), include)) {
						ClassModel model = ClassFile.of().parse(Files.readAllBytes(file));
						if (model.flags().has(AccessFlag.PUBLIC)) models.put(internal, model);
					}
				}
			}
		}

		if (models.isEmpty()) throw new BuildException("[bindings] include matched no public classes in Minecraft " + project.minecraft);

		Map<String, String> goNames = assignNames(models.keySet());
		StringBuilder source = new StringBuilder();
		source.append("// Code generated by go.jar genBindings from Minecraft ").append(project.minecraft).append(". DO NOT EDIT.\n\n");
		source.append("package ").append(packageName).append("\n\n");
		source.append("import \"github.com/GoCraftMC/gocraft-sdk/jvm\"\n\n");
		source.append("var _ jvm.Object\n\n");

		for (Map.Entry<String, ClassModel> entry : models.entrySet()) {
			generateClass(entry.getKey(), entry.getValue(), goNames, source);
		}

		Path dir = outRoot.resolve(packageName);
		Files2.deleteTree(dir);
		Files2.writeAtomic(dir.resolve("bindings.go"), source.toString().getBytes(StandardCharsets.UTF_8));
		Log.line("Generated bindings for " + models.size() + " classes in " + project.root.relativize(dir));
	}

	private static boolean matches(String className, List<String> patterns) {
		for (String pattern : patterns) {
			// a.b.* covers that package, a.b.** also its subpackages; nested classes follow their outer class.
			if (pattern.endsWith(".**")) {
				if (className.startsWith(pattern.substring(0, pattern.length() - 2))) return true;
			} else if (pattern.endsWith(".*")) {
				String prefix = pattern.substring(0, pattern.length() - 1);
				if (className.startsWith(prefix) && className.indexOf('.', prefix.length()) < 0) return true;
			} else if (className.equals(pattern) || className.startsWith(pattern + "$")) {
				return true;
			}
		}
		return false;
	}

	/** Short names where they are unique; otherwise qualified by the parent package. */
	private static Map<String, String> assignNames(Set<String> classes) {
		Map<String, Integer> counts = new HashMap<>();
		for (String internal : classes) counts.merge(shortName(internal), 1, Integer::sum);

		Map<String, String> names = new HashMap<>();
		Set<String> used = new HashSet<>();

		for (String internal : classes) {
			String name = shortName(internal);
			if (counts.get(name) > 1) {
				String[] parts = internal.split("/");
				name = exported(parts[Math.max(0, parts.length - 2)]) + name;
			}
			while (!used.add(name)) name += "_";
			names.put(internal, name);
		}
		return names;
	}

	private static String shortName(String internal) {
		String simple = internal.substring(internal.lastIndexOf('/') + 1);
		StringBuilder out = new StringBuilder();
		for (String part : simple.split("\\$")) {
			if (!part.isEmpty()) out.append(exported(part));
		}
		return out.toString();
	}

	private static String exported(String name) {
		String clean = name.replaceAll("[^A-Za-z0-9_]", "_");
		if (clean.isEmpty()) return "X";
		if (!Character.isLetter(clean.charAt(0))) clean = "X" + clean;
		return Character.toUpperCase(clean.charAt(0)) + clean.substring(1);
	}

	private record GoType(String param, String result, String resultExpr) { }

	private static GoType goType(ClassDesc desc, Map<String, String> names) {
		if (desc.isPrimitive()) {
			return switch (desc.descriptorString()) {
				case "I" -> new GoType("int32", "int32", "%s.Int()");
				case "J" -> new GoType("int64", "int64", "%s.Long()");
				case "Z" -> new GoType("bool", "bool", "%s.Bool()");
				case "F" -> new GoType("float32", "float32", "%s.Float()");
				case "D" -> new GoType("float64", "float64", "%s.Double()");
				case "B" -> new GoType("int8", "int8", "int8(%s.Int())");
				case "S" -> new GoType("int16", "int16", "int16(%s.Int())");
				case "C" -> new GoType("uint16", "uint16", "uint16(%s.Int())");
				default -> new GoType("", "", "");
			};
		}

		String descriptor = desc.descriptorString();
		if (descriptor.equals("Ljava/lang/String;")) return new GoType("string", "string", "%s.String()");

		if (descriptor.startsWith("L")) {
			String goName = names.get(descriptor.substring(1, descriptor.length() - 1));
			if (goName != null) return new GoType("jvm.Objecter", goName, "Wrap" + goName + "(%s.Object())");
		}
		return new GoType("jvm.Objecter", "jvm.Object", "%s.Object()");
	}

	private static void generateClass(String internal, ClassModel model, Map<String, String> names, StringBuilder out) {
		String goName = names.get(internal);
		String javaName = internal.replace('/', '.');
		String superName = model.superclass().map(s -> names.get(s.asInternalName())).orElse(null);

		out.append("// ").append(goName).append(" wraps ").append(javaName).append(".\n");
		if (superName != null) {
			out.append("type ").append(goName).append(" struct{ ").append(superName).append(" }\n\n");
			out.append("// Wrap").append(goName).append(" views a Java object as ").append(goName).append(".\n");
			out.append("func Wrap").append(goName).append("(o jvm.Objecter) ").append(goName).append(" { return ").append(goName).append("{Wrap").append(superName).append("(o)} }\n\n");
		} else {
			out.append("type ").append(goName).append(" struct{ jvm.Object }\n\n");
			out.append("// Wrap").append(goName).append(" views a Java object as ").append(goName).append(".\n");
			out.append("func Wrap").append(goName).append("(o jvm.Objecter) ").append(goName).append(" { return ").append(goName).append("{o.JavaObject()} }\n\n");
		}

		generateFields(internal, javaName, goName, model, names, out);
		generateMethods(javaName, goName, model, names, out);
	}

	private static void generateFields(String internal, String javaName, String goName, ClassModel model, Map<String, String> names, StringBuilder out) {
		int index = 0;
		for (FieldModel field : model.fields()) {
			if (!field.flags().has(AccessFlag.PUBLIC) || field.flags().has(AccessFlag.SYNTHETIC)) continue;

			GoType type = goType(field.fieldTypeSymbol(), names);
			String name = field.fieldName().stringValue();
			String descriptor = field.fieldType().stringValue();
			boolean isStatic = field.flags().has(AccessFlag.STATIC);
			String variable = "f_" + goName + "_" + index++;

			out.append("var ").append(variable).append(" = jvm.").append(isStatic ? "SF" : "F").append("(\"").append(javaName).append("\", \"").append(name).append("\", \"").append(descriptor).append("\")\n\n");
			if (isStatic) {
				out.append("// ").append(goName).append("_").append(name).append(" reads the static field ").append(name).append(".\n");
				out.append("func ").append(goName).append("_").append(name).append("() ").append(type.result).append(" { return ");
				out.append(String.format(type.resultExpr, variable + ".GetStatic()")).append(" }\n\n");
			} else {
				out.append("// Get").append(exported(name)).append(" reads the field ").append(name).append(".\n");
				out.append("func (o ").append(goName).append(") Get").append(exported(name)).append("() ").append(type.result).append(" { return ");
				out.append(String.format(type.resultExpr, variable + ".Get(o)")).append(" }\n\n");
			}
		}
	}

	private static void generateMethods(String javaName, String goName, ClassModel model, Map<String, String> names, StringBuilder out) {
		List<MethodModel> methods = new ArrayList<>();
		for (MethodModel method : model.methods()) {
			if (method.flags().has(AccessFlag.PUBLIC) && !method.flags().has(AccessFlag.SYNTHETIC) && !method.flags().has(AccessFlag.BRIDGE)) {
				String name = method.methodName().stringValue();
				if (!name.equals("<clinit>")) methods.add(method);
			}
		}
		methods.sort(Comparator.comparing((MethodModel m) -> m.methodName().stringValue()).thenComparing(m -> m.methodType().stringValue()));

		Set<String> used = new HashSet<>();
		int index = 0;

		for (MethodModel method : methods) {
			String javaMethod = method.methodName().stringValue();
			String descriptor = method.methodType().stringValue();
			MethodTypeDesc type = method.methodTypeSymbol();
			boolean isConstructor = javaMethod.equals("<init>");
			boolean isStatic = method.flags().has(AccessFlag.STATIC);
			String variable = "m_" + goName + "_" + index++;

			String baseName = isConstructor ? "New" : exported(javaMethod);
			String funcName = uniqueName(baseName, type, used, names);
			if (!isConstructor && !isStatic && RESERVED_METHODS.contains(funcName)) funcName = funcName + "_";

			StringBuilder params = new StringBuilder();
			StringBuilder args = new StringBuilder();
			for (int i = 0; i < type.parameterCount(); i++) {
				GoType param = goType(type.parameterType(i), names);
				String paramName = "a" + i;
				if (i > 0) params.append(", ");
				params.append(paramName).append(" ").append(param.param);
				args.append(", ").append(paramName);
			}

			if (isConstructor) {
				out.append("var ").append(variable).append(" = jvm.Ctor(\"").append(javaName).append("\", \"").append(descriptor).append("\")\n\n");
				out.append("// ").append(goName).append("_").append(funcName).append(" constructs a ").append(goName).append(".\n");
				out.append("func ").append(goName).append("_").append(funcName).append("(").append(params).append(") ").append(goName).append(" {\n");
				out.append("\treturn Wrap").append(goName).append("(").append(variable).append(".CallStatic(").append(trimLeadingComma(args)).append(").Object())\n}\n\n");
				continue;
			}

			GoType ret = goType(type.returnType(), names);
			boolean isVoid = type.returnType().descriptorString().equals("V");
			String call = variable + (isStatic ? ".CallStatic(" + trimLeadingComma(args) + ")" : ".Call(o" + args + ")");

			out.append("var ").append(variable).append(" = jvm.").append(isStatic ? "SM" : "M").append("(\"").append(javaName).append("\", \"").append(javaMethod).append("\", \"").append(descriptor).append("\")\n\n");
			out.append("// ");
			if (isStatic) out.append(goName).append("_");
			out.append(funcName).append(" calls ").append(javaMethod).append(descriptor).append(".\n");
			out.append("func ");
			if (isStatic) out.append(goName).append("_").append(funcName);
			else out.append("(o ").append(goName).append(") ").append(funcName);
			out.append("(").append(params).append(") ").append(ret.result).append(" {\n\t");
			if (isVoid) out.append(call);
			else out.append("return ").append(String.format(ret.resultExpr, call));
			out.append("\n}\n\n");
		}
	}

	private static String trimLeadingComma(StringBuilder args) {
		return args.isEmpty() ? "" : args.substring(2);
	}

	private static String uniqueName(String base, MethodTypeDesc type, Set<String> used, Map<String, String> names) {
		String name = base;
		if (KEYWORDS.contains(name)) name = name + "_";
		if (used.add(name)) return name;

		StringBuilder suffix = new StringBuilder(base);
		for (int i = 0; i < type.parameterCount(); i++) {
			suffix.append('_').append(exported(type.parameterType(i).displayName().replace("[]", "Array")));
		}
		String overloaded = suffix.toString();
		while (!used.add(overloaded)) overloaded += "_";
		return overloaded;
	}
}
